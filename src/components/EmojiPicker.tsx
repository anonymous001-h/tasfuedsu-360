const CATEGORY_ICONS: Record<string, string> = {
  Smileys: '😀',
  Gestures: '👋',
  Love: '❤️',
  Animals: '🐶',
  Food: '🍎',
  Activities: '⚽',
  Travel: '✈️',
  Objects: '💡',
  Symbols: '✨',
  Flags: '🏁',
};

interface EmojiPickerProps {
  open: boolean;
  onClose: () => void;
  onEmojiSelect: (emoji: string) => void;
}

export function EmojiPicker({ open, onClose, onEmojiSelect }: EmojiPickerProps) {
  const [activeCategory, setActiveCategory] = useState(0);
  const [search, setSearch] = useState('');
  const scrollRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (open) {
      setSearch('');
      setActiveCategory(0);
    }
  }, [open]);

  if (!open) return null;

  const filtered = search.trim()
    ? CATEGORIES.flatMap((c) => c.emojis).filter((e) => e.includes(search.trim()))
    : CATEGORIES[activeCategory].emojis;

  return (
    <div className="flex-shrink-0 flex flex-col bg-white dark:bg-dark-surface border-t border-navy-100 dark:border-dark-border animate-slide-up" style={{ height: 'min(320px, 45vh)' }}>
      {/* Header */}
      <div className="flex items-center gap-2 px-3 py-2 border-b border-navy-100 dark:border-dark-border flex-shrink-0">
        <div className="relative flex-1">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-navy-400" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search emoji..."
            className="w-full pl-9 pr-3 py-2 rounded-lg bg-navy-50 dark:bg-dark-bg border border-navy-100 dark:border-dark-border text-navy-800 dark:text-dark-text text-xs outline-none focus:border-brand-400"
          />
        </div>
        <button onClick={onClose} className="w-8 h-8 rounded-lg flex items-center justify-center text-navy-400 hover:bg-navy-100 dark:hover:bg-dark-surface2 active:scale-90 transition-all flex-shrink-0">
          <X className="w-4 h-4" />
        </button>
      </div>

      {/* Emoji grid */}
      <div ref={scrollRef} className="flex-1 overflow-y-auto px-2 py-2 scrollbar-hide">
        {filtered.length === 0 ? (
          <p className="text-center text-xs text-navy-400 py-8">No emojis found</p>
        ) : (
          <div className="grid grid-cols-8 gap-0.5">
            {filtered.map((emoji, i) => (
              <button
                key={`${emoji}-${i}`}
                type="button"
                onMouseDown={(e) => e.preventDefault()}
                onClick={() => onEmojiSelect(emoji)}
                className="text-xl h-9 w-9 flex items-center justify-center rounded-lg hover:bg-navy-100 dark:hover:bg-dark-surface2 active:scale-110 transition-all"
              >
                {emoji}
              </button>
            ))}
          </div>
        )}
      </div>

      {/* Category tabs */}
      {!search.trim() && (
        <div className="flex-shrink-0 flex items-center gap-0.5 px-2 py-1.5 border-t border-navy-100 dark:border-dark-border overflow-x-auto scrollbar-hide">
          {CATEGORIES.map((cat, i) => (
            <button
              key={cat.name}
              onClick={() => { setActiveCategory(i); scrollRef.current?.scrollTo({ top: 0 }); }}
              className={`w-9 h-9 flex items-center justify-center rounded-lg text-base transition-all flex-shrink-0 ${
                activeCategory === i
                  ? 'bg-brand-100 dark:bg-brand-900/30 scale-110'
                  : 'hover:bg-navy-50 dark:hover:bg-dark-surface2 opacity-60'
              }`}
              aria-label={cat.name}
            >
              {CATEGORY_ICONS[cat.name]}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
